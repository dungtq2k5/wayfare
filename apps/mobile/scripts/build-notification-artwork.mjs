// The picture the media notification shows for a Place without a photo: the app icon, small. The
// notification reads an image from a file or a web address, and a bundled asset is neither in a
// release build, so the icon is embedded as text and written to a file when the player first needs
// it. `pnpm --filter @wayfare/mobile notification-artwork` writes src/player/generated/notification-artwork.ts.
import { mkdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

const png = await sharp(new URL('../assets/brand/icon.png', import.meta.url).pathname)
  .resize(256, 256)
  .png({ compressionLevel: 9 })
  .toBuffer();

mkdirSync(new URL('../src/player/generated/', import.meta.url), { recursive: true });
writeFileSync(
  new URL('../src/player/generated/notification-artwork.ts', import.meta.url),
  `// Generated by scripts/build-notification-artwork.mjs: do not edit.\nexport const NOTIFICATION_ARTWORK_BASE64 =\n  '${png.toString('base64')}';\n`,
);
