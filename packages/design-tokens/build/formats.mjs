import { FONT_FILES, buildModel, hexToChannels } from './model.mjs';

const HEADER = '// Generated by Style Dictionary from tokens.json. Do not edit.\n';
const json = (value) => JSON.stringify(value, null, 2);

/** `fontSize` utilities keep their line height, as Tailwind's tuple does. */
function presetSource(model) {
  const channels = (mode) =>
    Object.fromEntries(
      Object.entries(model.colors[mode]).map(([name, hex]) => [`--${name}`, hexToChannels(hex)]),
    );
  const colors = Object.fromEntries(
    Object.keys(model.colors.light).map((name) => [name, `rgb(var(--${name}) / <alpha-value>)`]),
  );
  const px = (n) => `${n}px`;
  const pxMap = (map) => Object.fromEntries(Object.entries(map).map(([k, v]) => [k, px(v)]));
  const textStyles = Object.fromEntries(
    Object.entries(model.typography)
      // Tabular figures (numeric) cannot be a class: NativeWind turns font-variant into a style React
      // Native ignores. The component that shows numbers sets style={{ fontVariant: ['tabular-nums'] }}.
      // body-small is web-only: the phone's smallest text is caption (handoff).
      .filter(([name]) => name !== 'body-small')
      .map(([name, style]) => [
        `.text-${name}`,
        {
          fontSize: px(style.fontSize),
          lineHeight: px(style.lineHeight),
          fontFamily: style.fontFamily,
        },
      ]),
  );
  return `${HEADER}const plugin = require('tailwindcss/plugin');

const light = ${json(channels('light'))};
const dark = ${json(channels('dark'))};

module.exports = {
  theme: {
    // Replaces Tailwind's palette: only the semantic tokens exist, so bg-emerald-700 does not.
    colors: {
      transparent: 'transparent',
      current: 'currentColor',
      ...${json(colors)},
    },
    spacing: ${json(pxMap(model.space))},
    borderRadius: ${json(pxMap(model.radius))},
    fontSize: ${json(
      Object.fromEntries(
        Object.entries(model.fontSize).map(([k, v]) => [
          k,
          [px(v.size), { lineHeight: px(v.lineHeight) }],
        ]),
      ),
    )},
    fontFamily: { sans: ${json(FONT_FILES[400])} },
    elevation: ${json(Object.fromEntries(Object.entries(model.elevation).map(([k, v]) => [k, String(v)])))},
    extend: {
      minHeight: { target: ${json(px(model.size['target-min']))} },
      minWidth: { target: ${json(px(model.size['target-min']))} },
    },
  },
  plugins: [
    plugin(({ addBase, addUtilities }) => {
      addBase({ ':root': light, '@media (prefers-color-scheme: dark)': { ':root': dark } });
      addUtilities(${json(textStyles)});
    }),
  ],
};
`;
}

function valuesSource(model) {
  return `${HEADER}module.exports = ${json({
    colors: model.colors,
    space: model.space,
    radius: model.radius,
    fontSize: model.fontSize,
    typography: model.typography,
    elevation: model.elevation,
    duration: model.duration,
    size: model.size,
    fontFiles: FONT_FILES,
  })};
`;
}

function declarationSource(model) {
  const names = (map) =>
    Object.keys(map)
      .map((key) => JSON.stringify(key))
      .join(' | ');
  return `${HEADER}export type SemanticColor = ${names(model.colors.light)};
export type TextStyle = ${names(model.typography)};
export interface TypographyToken { fontSize: number; lineHeight: number; fontFamily: string; fontWeight: number }
export declare const colors: { light: Record<SemanticColor, string>; dark: Record<SemanticColor, string> };
export declare const space: Record<${names(model.space)}, number>;
export declare const radius: Record<${names(model.radius)}, number>;
export declare const fontSize: Record<${names(model.fontSize)}, { size: number; lineHeight: number }>;
export declare const typography: Record<TextStyle, TypographyToken>;
export declare const elevation: Record<${names(model.elevation)}, number>;
/** Milliseconds. */
export declare const duration: Record<${names(model.duration)}, number>;
export declare const size: Record<${names(model.size)}, number>;
export declare const fontFiles: Record<400 | 500 | 600 | 700, string>;
`;
}

const rem = (px) => (px === 0 ? '0' : px > 1000 ? `${px}px` : `${px / 16}rem`);

function webSource(model, shadows) {
  const vars = (mode) =>
    Object.entries(model.colors[mode])
      .map(([name, hex]) => `  --${name}: ${hex};`)
      .join('\n');
  const theme = [
    ...Object.keys(model.colors.light).map((name) => `  --color-${name}: var(--${name});`),
    ...Object.entries(model.radius).map(([k, v]) => `  --radius-${k}: ${rem(v)};`),
    ...Object.entries(model.fontSize).flatMap(([k, v]) => [
      `  --text-${k}: ${rem(v.size)};`,
      `  --text-${k}--line-height: ${rem(v.lineHeight)};`,
    ]),
    `  --font-sans: "Be Vietnam Pro", sans-serif;`,
    `  --spacing: ${rem(model.space['1'])};`,
    ...Object.entries(shadows).map(([k, v]) => `  --shadow-${k}: ${v};`),
    ...Object.entries(model.duration).map(([k, v]) => `  --duration-${k}: ${v}ms;`),
  ].join('\n');
  return `/* Generated by Style Dictionary from tokens.json. Do not edit. */
:root {
${vars('light')}
}

.dark {
${vars('dark')}
}

@theme inline {
${theme}
}
`;
}

/** The format functions Style Dictionary registers. */
export const formats = {
  'wayfare/nativewind-preset': ({ dictionary }) => presetSource(buildModel(dictionary.allTokens)),
  'wayfare/values': ({ dictionary }) => valuesSource(buildModel(dictionary.allTokens)),
  'wayfare/values-d-ts': ({ dictionary }) => declarationSource(buildModel(dictionary.allTokens)),
  'wayfare/web-css': ({ dictionary }) => {
    const shadows = Object.fromEntries(
      dictionary.allTokens
        .filter((token) => token.path[0] === 'shadow')
        .map((token) => {
          const { offsetX, offsetY, blur, spread, color } = token.$value;
          return [token.path[1], `${offsetX} ${offsetY} ${blur} ${spread} ${color}`];
        }),
    );
    return webSource(buildModel(dictionary.allTokens), shadows);
  },
};
